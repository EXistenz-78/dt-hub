#!/usr/bin/env python3
"""Builds Packages/Sources/DTBridge/VideoModelSpecs.swift from Draw Things' community model list.

usage: make-video-specs.py COMMUNITY_MODELS_JSON [OUT_SWIFT]

COMMUNITY_MODELS_JSON is a local copy of https://kcjerrell.github.io/dt-models/community_models.json (download it by
hand: this script does not use the network); OUT_SWIFT defaults to Packages/Sources/DTBridge/VideoModelSpecs.swift next
to this script's repository.

The Swift file keeps the specification of the video models DT Hub can run, as JSON strings by file name: the entries
whose `version` is `minimax_h3` and the FastH3 ones (`file` starting with `fasth3_omni`). The app registers them for the
files its own lists do not describe. Regenerate with:

    python3 -I Scripts/make-video-specs.py community_models.json
"""
import json
import os
import sys

DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "Packages", "Sources", "DTBridge", "VideoModelSpecs.swift")


def wanted(entry):
    """True for the entries of the families DT Hub generates video with."""
    if not isinstance(entry, dict) or not isinstance(entry.get("file"), str):
        return False
    return entry.get("version") == "minimax_h3" or entry["file"].startswith("fasth3_omni")


def raw_delimiter(texts):
    """The shortest run of `#` that makes `#"..."#` safe for all of the texts."""
    count = 1
    while any(('"' + "#" * count) in text or ("\\" + "#" * count) in text for text in texts):
        count += 1
    return "#" * count


def render(entries):
    """The text of VideoModelSpecs.swift for the entries (a dictionary file -> spec object)."""
    texts = {file: json.dumps(entry, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
             for file, entry in sorted(entries.items())}
    hashes = raw_delimiter(list(texts.values()))
    lines = [
        "// Generated by Scripts/make-video-specs.py from Draw Things' community_models.json: do not edit by hand.",
        "// Regenerate with: python3 -I Scripts/make-video-specs.py community_models.json",
        "import Foundation",
        "",
        "/// The specification of the video models DT Hub can run (H3 and FastH3), by file name, as JSON.",
        "enum VideoModelSpecs {",
        "  static let byFile: [String: String] = [",
    ]
    for file, text in texts.items():
        lines.append(f'    "{file}": {hashes}"{text}"{hashes},')
    lines += [
        "  ]",
        "",
        "  /// The specification of a file, as JSON data; nil when it is not a bundled video model.",
        "  static func data(for file: String) -> Data? {",
        "    byFile[file].map { Data($0.utf8) }",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    with open(argv[1], encoding="utf-8") as source:
        entries = {entry["file"]: entry for entry in json.load(source) if wanted(entry)}
    if not entries:
        sys.exit("no video model in " + argv[1])
    out = argv[2] if len(argv) > 2 else DEFAULT_OUT
    with open(out, "w", encoding="utf-8") as target:
        target.write(render(entries))
    print(f"{len(entries)} video models -> {out}")


if __name__ == "__main__":
    main(sys.argv)
