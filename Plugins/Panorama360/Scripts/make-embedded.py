#!/usr/bin/env python3
"""make-embedded.py — mette Data/master-prompt.md in Sources/Panorama360/Embedded/PSEmbedded.swift.

Un bundle contiene solo la libreria, quindi il file dei dati sta anche nel codice come stringa Swift. Si lancia da qualsiasi
cartella; l'uscita è deterministica (un test controlla che le due copie siano uguali).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(HERE)
source = open(os.path.join(PLUGIN, "Data", "master-prompt.md"), encoding="utf-8").read()
assert '"""#' not in source
out = os.path.join(PLUGIN, "Sources", "Panorama360", "Embedded", "PSEmbedded.swift")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by Scripts/make-embedded.py: do not edit.\n")
    f.write("// Il master prompt come stringa: un bundle contiene solo la libreria.\n\n")
    f.write("enum PSEmbedded {\n  static let masterPrompt = #\"\"\"\n")
    f.write(source if source.endswith("\n") else source + "\n")
    f.write("\"\"\"#\n}\n")
