#!/usr/bin/env python3
"""make-f3-data.py — costruisce i dati del plug-in Prompt Master F3.

Il vocabolario è quello di Prompt Master (Plugins/PromptMaster/Data/prompt-database.json, copiato com'è, mai modificato).
Il resto si scrive qui: i gruppi esclusi, le categorie solo-Foto e solo-Arte, le opzioni dell'LLM e il master prompt.
Scrive, sotto Plugins/PromptMasterF3:
  Data/prompt-database.json   il vocabolario condiviso
  Data/flux3.json             configurazione
  Data/master-prompt.md       il master prompt (Markdown)
  Sources/PromptMasterF3/Embedded/EmbeddedData.swift   i tre file come stringhe Swift (un bundle non ha risorse)
Si lancia da qualsiasi cartella; l'uscita è deterministica.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(HERE)
SHARED = os.path.join(os.path.dirname(PLUGIN), "PromptMaster", "Data", "prompt-database.json")

CONFIG_VERSION = "1.0.0"
EXCLUDED_GROUPS = ["H"]
# Come in Prompt Master I4: queste categorie esistono solo con Foto, quelle sotto solo con Arte.
PHOTO_ONLY = ["framing", "camera_angle", "composition", "lens_focus", "photo_genre", "film_stock_process", "optical_fx"]
ART_ONLY = ["medium_paint_draw", "medium_print_craft", "art_movement", "design_movement", "anime_cartoon_style",
            "cultural_tradition", "artist_classical", "artist_modern", "artist_illustration"]
OPTIONS = {"temperature": 0.6, "maxTokens": 4096, "thinking": False, "timeout": 600}

SYSTEM = """You prepare the text of a structured image prompt for the image model FLUX.3. The request has blocks, each under a title: "description" (the whole picture), "composition" (a sentence that names the elements of the picture with placeholders such as <woman_1>) and one "element: <id>" block for each element (what must appear inside that element's region).

Answer with the SAME titles, in the SAME order, each followed by its rewritten text. Write nothing else: no JSON, no notes, no markdown other than the titles.

Rules:
1. Write in English, whatever language the input is in. Plain descriptive prose, no commands, no keyword lists, no labels.
2. NEVER change, translate, remove, add, move to another place or rename anything between < and >. Each placeholder stays exactly as written, the same number of times. Only translate and enrich the words around them.
3. Words between quotation marks are text to be printed in the picture: copy them exactly.
4. "description": one or two sentences about the scene as a whole. Lines shaped like "Category: term" are terms picked from a vocabulary; work them into the sentence naturally. Do not describe the individual elements here.
5. "composition": keep it a short sentence that places the elements in the scene; do not describe them in detail.
6. "element: <id>": describe only what appears inside that region: appearance, material, colour, pose, in a few concrete sentences. No positions, no coordinates, no mention of other elements.
7. Do not invent new elements, and do not add placeholders.

Example. Request:
## description
due amici in una tavola calda, di notte
Lighting Scheme: Rim light

## composition
Ci sono una donna <woman_1> e un ombrello <umbrella_1>.

## element: woman_1
una giovane donna con un trench nero

## element: umbrella_1
ombrello rosso

Reply in exactly this shape:
## description
...

## composition
...

## element: woman_1
...

## element: umbrella_1
..."""


def swift_literal(name, text):
    assert '"""#' not in text
    return f'  static let {name} = #"""\n{text}\n"""#\n'


if __name__ == "__main__":
    with open(SHARED) as source:
        database_text = json.dumps(json.load(source), ensure_ascii=False, indent=1, sort_keys=False) + "\n"
    config = {"schema": 1, "version": CONFIG_VERSION, "excludedGroups": EXCLUDED_GROUPS, "photoOnly": PHOTO_ONLY,
              "artOnly": ART_ONLY, "options": OPTIONS}
    config_text = json.dumps(config, ensure_ascii=False, indent=1, sort_keys=False) + "\n"
    master_text = "---\nversion: 1\n---\n" + SYSTEM.rstrip("\n")
    os.makedirs(os.path.join(PLUGIN, "Data"), exist_ok=True)
    with open(os.path.join(PLUGIN, "Data", "master-prompt.md"), "w") as out:
        out.write(master_text + "\n")
    for name, text in (("prompt-database", database_text), ("flux3", config_text)):
        with open(os.path.join(PLUGIN, "Data", name + ".json"), "w") as out:
            out.write(text)
    embedded = os.path.join(PLUGIN, "Sources", "PromptMasterF3", "Embedded")
    os.makedirs(embedded, exist_ok=True)
    with open(os.path.join(embedded, "EmbeddedData.swift"), "w") as out:
        out.write("// Generated by Scripts/make-f3-data.py: do not edit.\n"
                  "// I file dei dati del plug-in come stringhe: un bundle contiene solo la libreria.\n\n"
                  "enum EmbeddedData {\n" + swift_literal("database", database_text.rstrip("\n"))
                  + "\n" + swift_literal("flux3", config_text.rstrip("\n"))
                  + "\n" + swift_literal("masterPrompt", master_text) + "}\n")
    print(f"flux3 {CONFIG_VERSION}: {len(PHOTO_ONLY)} solo-Foto, {len(ART_ONLY)} solo-Arte, esclusi {EXCLUDED_GROUPS}")
