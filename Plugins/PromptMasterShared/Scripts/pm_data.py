"""What the data scripts of the Prompt Master plug-ins share: how a text becomes a Swift raw string and where the files go.

The vocabulary (Plugins/PromptMaster/Data/prompt-database.json) is embedded once, in
PromptMasterShared/Vocabulary/EmbeddedVocabulary.swift, by PromptMaster/Scripts/make-prompt-data.py. Every plug-in compiles
that folder into its own library (the `Shared` link in its sources), so each bundle still holds its own copy.
"""
import json, os

SHARED = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLUGINS = os.path.dirname(SHARED)
VOCABULARY = os.path.join(PLUGINS, "PromptMaster", "Data", "prompt-database.json")
EMBEDDED_VOCABULARY = os.path.join(SHARED, "Vocabulary", "EmbeddedVocabulary.swift")


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=1, sort_keys=False) + "\n"


def swift_literal(name, text):
    assert '"""#' not in text
    return f'  static let {name} = #"""\n{text}\n"""#\n'


def write_swift(path, script, comment, enum, literals):
    """Writes `enum <enum>` with one raw string per (name, text) pair."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as out:
        out.write(f"// Generated by {script}: do not edit.\n// {comment}\n\n"
                  f"enum {enum} {{\n" + "\n".join(swift_literal(name, text) for name, text in literals) + "}\n")


def write_vocabulary(text):
    """The vocabulary as the one Swift string all the Prompt Master plug-ins compile."""
    write_swift(EMBEDDED_VOCABULARY, "PromptMaster/Scripts/make-prompt-data.py",
                "The vocabulary as a string: a plug-in bundle holds only its library.", "EmbeddedVocabulary",
                [("database", text.rstrip("\n"))])


def write_plugin_data(plugin, script, config_name, config, master_version, system):
    """The files of one plug-in: Data/<config_name>.json, Data/master-prompt.md and Embedded/EmbeddedData.swift."""
    folder = os.path.join(PLUGINS, plugin)
    config_text = json_text(config)
    master_text = f"---\nversion: {master_version}\n---\n" + system.rstrip("\n")
    os.makedirs(os.path.join(folder, "Data"), exist_ok=True)
    with open(os.path.join(folder, "Data", "master-prompt.md"), "w") as out:
        out.write(master_text + "\n")
    with open(os.path.join(folder, "Data", config_name + ".json"), "w") as out:
        out.write(config_text)
    write_swift(os.path.join(folder, "Sources", plugin, "Embedded", "EmbeddedData.swift"), f"Scripts/{script}",
                "The data files of the plug-in as strings: a plug-in bundle holds only its library.", "EmbeddedData",
                [(config_name, config_text.rstrip("\n")), ("masterPrompt", master_text)])
